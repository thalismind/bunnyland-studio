@pytest.mark.asyncio
async def test_open_map_client_bounds_and_caches_service_calls(monkeypatch):
    calls: list[tuple[str, str]] = []

    class Response:
        def __init__(self, payload: object) -> None:
            self.payload = payload

        def raise_for_status(self) -> None:
            return None

        def json(self) -> object:
            return self.payload

    class Client:
        def __init__(self, **_options: object) -> None:
            pass

        async def __aenter__(self):
            return self

        async def __aexit__(self, *_args: object) -> None:
            return None

        async def get(self, url: str, **_options: object) -> Response:
            calls.append(("get", url))
            if "/search" in url:
                return Response(
                    [
                        {
                            "osm_type": "node",
                            "osm_id": 42,
                            "display_name": "Rose Junction",
                            "lat": "35.0",
                            "lon": "-105.0",
                        }
                    ]
                )
            return Response({"routes": [{"distance": 123400, "duration": 7200}]})

        async def post(self, url: str, **_options: object) -> Response:
            calls.append(("post", url))
            return Response(
                {
                    "elements": [
                        {
                            "type": "way",
                            "id": 9,
                            "center": {"lat": 35.1, "lon": -104.9},
                            "tags": {"amenity": "fuel", "name": "Roadrunner Fuel"},
                        }
                    ]
                }
            )

    monkeypatch.setattr("bunnyland_studio.generators.httpx.AsyncClient", Client)
    client = OpenMapClient(
        nominatim_url="https://nominatim.invalid",
        osrm_url="https://osrm.invalid",
        overpass_url="https://overpass.invalid",
        contact="operator@example.invalid",
    )
    point = GeoPoint(latitude=35, longitude=-105)

    first_search = await client.search("Rose Junction", limit=99)
    second_search = await client.search("Rose Junction", limit=99)
    first_route = await client.route(point, GeoPoint(latitude=36, longitude=-104))
    second_route = await client.route(point, GeoPoint(latitude=36, longitude=-104))
    pois = await client.pois(point, radius_meters=999_999)

    assert first_search == second_search and first_search[0].osm_id == 42
    assert first_route == second_route == RouteEstimate(123.4, 120)
    assert pois[0].tags["amenity"] == "fuel"
    assert len([call for call in calls if call[0] == "get"]) == 2
    assert calls[-1] == ("post", "https://overpass.invalid")


