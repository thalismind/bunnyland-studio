def _command(character, controller, command_type: str, payload: dict[str, object]):
    edge = character.get_relationships(ControlledBy)[0][0]
    return SubmittedCommand(
        command_id=f"test-{command_type}",
        character_id=str(character.id),
        controller_id=str(controller.id),
        controller_generation=edge.generation,
        command_type=command_type,
        payload=payload,
        cost=CommandCost(),
        lane=Lane.WORLD,
        on_insufficient_points=OnInsufficientPoints.DENY,
        submitted_at_epoch=0,
    )


def _owned(actor: WorldActor, character, kind: str):
    return [
        actor.world.get_entity(target)
        for edge, target in character.get_relationships(StudioOwns)
        if edge.kind == kind and actor.world.has_entity(target)
    ]


