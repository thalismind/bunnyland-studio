def test_refuel_action_requires_a_mapped_fuel_stop():
    actor, character, controller, _destination = _studio_world()
    handler = RefuelHandler()
    context = HandlerContext(actor.world, epoch=1, actor=actor)

    rejected_result = handler.execute(
        context, _command(character, controller, "studio-van-refuel", {"liters": 10})
    )
    assert not rejected_result.ok and rejected_result.reason == "refueling requires a fuel stop"

    rose = next(
        entity
        for entity in actor.world.query().with_all([StudioLocationComponent]).execute_entities()
        if entity.get_component(StudioLocationComponent).location_id == "rose"
    )
    place = rose.get_component(StudioLocationComponent)
