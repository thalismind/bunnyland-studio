def test_owner_scoped_http_projection_and_admin_reset():
    actor, character, controller, _destination = _studio_world()
    store = TokenStore(":memory:")
    owner_token, _owner = store.issue("owner-a", (WORLD_PLAY_SCOPE,), automatic_rotation=False)
    other_token, _other = store.issue("owner-b", (WORLD_PLAY_SCOPE,), automatic_rotation=False)
    admin_token, _admin = store.issue(
        "operator", (WORLD_PLAY_SCOPE, WORLD_ADMIN_SCOPE), automatic_rotation=False
    )
    app = create_app(actor, plugins=[plugin()], token_store=store)
    client = TestClient(app)
    owner_headers = {
        "Authorization": f"Bearer {owner_token}",
        "X-Bunnyland-Client-Id": "studio-web",
    }

    claimed = client.post(
        "/v1/play/extensions/bunnyland.studio/claims",
        headers=owner_headers,
        json={"character_id": str(character.id)},
    )
    assert claimed.status_code == 201
    assert claimed.json()["autonomous_controller_active"] is True
    assert character.get_relationships(ControlledBy)[0][1] == controller.id

    projection = client.get(
        "/v1/play/extensions/bunnyland.studio/projection", headers=owner_headers
    )
    assert projection.status_code == 200
    assert projection.json()["character_name"] == "Mira"

    empty_memories = client.get(
        "/v1/play/extensions/bunnyland.studio/memories", headers=owner_headers
    )
    assert empty_memories.status_code == 200
    assert empty_memories.json() == []
    created_memory = client.post(
        "/v1/play/extensions/bunnyland.studio/memories",
        headers=owner_headers,
        json={"text": "Inez heard the belt squeal.", "tags": ["mechanic"]},
    )
    assert created_memory.status_code == 201
    assert created_memory.json()["text"] == "Inez heard the belt squeal."
    assert created_memory.json()["tags"] == ["mechanic", "studio"]
    memories = client.get("/v1/play/extensions/bunnyland.studio/memories", headers=owner_headers)
    assert memories.status_code == 200
    assert memories.json() == [created_memory.json()]

    reflection = client.post(
        "/v1/play/extensions/bunnyland.studio/journal/reflections",
        headers=owner_headers,
        json={"text": "I will remember the sound."},
    )
    assert reflection.status_code == 201
    moment_id = reflection.json()["id"]
    pinned = client.put(
        f"/v1/play/extensions/bunnyland.studio/journal/{moment_id}/pin",
        headers=owner_headers,
    )
    assert pinned.status_code == 200
    assert pinned.json()["pinned"] is True
    unpinned = client.delete(
        f"/v1/play/extensions/bunnyland.studio/journal/{moment_id}/pin",
        headers=owner_headers,
    )
    assert unpinned.status_code == 200
    assert unpinned.json()["pinned"] is False
    assert (
        client.put(
            "/v1/play/extensions/bunnyland.studio/journal/missing/pin",
            headers=owner_headers,
        ).status_code
        == 404
    )
    assert (
        client.delete(
            "/v1/play/extensions/bunnyland.studio/journal/missing/pin",
            headers=owner_headers,
        ).status_code
        == 404
    )

    denied = client.get(
        "/v1/play/extensions/bunnyland.studio/projection",
        headers={
            "Authorization": f"Bearer {other_token}",
            "X-Bunnyland-Client-Id": "studio-web",
        },
    )
    assert denied.status_code == 403
    denied_memories = client.get(
        "/v1/play/extensions/bunnyland.studio/memories",
        headers={
            "Authorization": f"Bearer {other_token}",
            "X-Bunnyland-Client-Id": "studio-web",
        },
    )
    assert denied_memories.status_code == 403

    memory_store = actor.memory_store
    actor.memory_store = None
    unavailable_memories = client.get(
        "/v1/play/extensions/bunnyland.studio/memories", headers=owner_headers
    )
    assert unavailable_memories.status_code == 503
    actor.memory_store = memory_store

    stock_claim = client.post(
        "/v1/play/claims",
        headers={**owner_headers, "X-Bunnyland-Client-Id": "studio-web"},
        json={"character_id": str(character.id), "delivery": "header"},
    )
    assert stock_claim.status_code == 409
    assert stock_claim.json()["detail"] == CLAIM_REJECTION

    reset = client.delete(
        f"/v1/admin/extensions/bunnyland.studio/claims/{character.id}",
        headers={
            "Authorization": f"Bearer {admin_token}",
            "X-Bunnyland-Client-Id": "studio-admin",
        },
    )
    assert reset.status_code == 200
    assert not character.has_component(StudioInfluenceClaimComponent)
